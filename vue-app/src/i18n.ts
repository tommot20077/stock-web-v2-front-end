export const t = (lang: Lang, k: string): string => I18N[lang]?.[k] ?? k;

/**
 * 含佔位符的文案取值:把 `{name}` 全數替換為 `String(vars[name])`;`vars` 沒提供的佔位符原樣保留。
 *
 * zh / en 語序不同,含變數的文案不能用字串串接,所以佔位符寫在文案裡、由呼叫端傳值。
 * 不引入 i18n 套件(UI-SPEC U-15)。未知的 key 與 `t()` 一致,退回 key 本身。
 */
export const tf = (lang: Lang, k: string, vars: Record<string, string | number>): string =>
  t(lang, k).replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : placeholder);
